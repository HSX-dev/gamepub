// devkeys 生成本地开发用的随机密钥，输出 .env 格式：go run ./tools/devkeys > .env
//
// 仅用于本地开发。生产密钥由密钥管理系统（KMS / Vault）生成，经 External Secrets 写入 K8s Secret，
// 各服务只挂载自己需要的那一份。
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"fmt"
)

func random(n int) []byte {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return b
}

func main() {
	seed := random(ed25519.SeedSize)
	pub, _ := ed25519.NewKeyFromSeed(seed).Public().(ed25519.PublicKey)
	b64 := base64.StdEncoding.EncodeToString

	fmt.Println("# generated by tools/devkeys — local development only, never commit")
	fmt.Println("JWT_ED25519_SEED=" + b64(seed))
	fmt.Println("JWT_ED25519_PUBLIC=" + b64(pub))
	fmt.Println("PII_AES_KEY=" + b64(random(32)))
	fmt.Println("PHONE_PEPPER=" + hex.EncodeToString(random(24)))
	fmt.Println("INTERNAL_TOKEN=" + hex.EncodeToString(random(32)))
	fmt.Println("PAY_MOCKPAY_SECRET=" + hex.EncodeToString(random(32)))
	fmt.Println("DELIVERY_SIGN_SECRET=" + hex.EncodeToString(random(32)))
	fmt.Println("REDIS_PASSWORD=" + hex.EncodeToString(random(16)))
	fmt.Println("MYSQL_ROOT_PASSWORD=" + hex.EncodeToString(random(16)))
	for _, svc := range []string{"ACCOUNT", "WALLET", "ORDER", "TASK"} {
		fmt.Printf("%s_DB_PASSWORD=%s\n", svc, hex.EncodeToString(random(16)))
	}
}
